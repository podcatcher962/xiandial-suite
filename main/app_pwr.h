#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"
#include "esp_sleep.h"

/* ============================================================
 *  拾声 (XianDial) 硬件版 —— 电源 / 关机 / 状态灯
 * ============================================================
 *  板型 LCD Wiki ES3C35P（10-04 读原理图定案）：
 *
 *  供电路径（02_原理图.pdf 实读，别再猜）
 *  -----------------------------------------
 *      锂电 3.7V ─JP1─ BAT+ ─Q3(SL2305 P-MOS)─┐
 *                                                 ├─ +5V 主电源轨
 *      USB Type-C 5V ──D8(B5819W 肖特基)───────┘        │
 *                                            ┌──────────┴──────────┐
 *                              U3 ME6217C33(LDO)         U4 ME6217C33(LDO)
 *                                 → VCC3V3 主供电            → AU_VCC3V3
 *
 *  ★★★ 三个必须记住的硬件事实 ★★★
 *
 *  ① ⛔ **TP4054 没有过放保护**。R12=3.3K 只设定【充电电流约 290 mA】，
 *     电池放到 ~2.5V 它不会切断 ⇒ 过放会永久损伤甚至起火。
 *     **所以配电池必须选带保护板的锂电**（充电管理 ≠ 保护电路）。
 *
 *  ② ⚠️ **全程 LDO**。4.2V→3.3V 的 0.9V 压在 ME6217 上，整机 0.4A 时
 *     白扔 0.36W（占输入功率 24%）⇒ 1000mAh 电池实际只 ≈2 小时。
 *     ⚠️ 别误读成「电池满电会掉到 3.6V」——**LDO 输出恒为 3.3V，是稳的**；
 *     真正的失效点是 Vin 掉到约 3.2V 以下才顶不住 3.3V。
 *     连带现象：功放 SC8002 吃的是 +5V ⇒ **电放少了音量会变小**。
 *
 *  ③ ★★ **Q3 的栅极被 R13 100K 下拉到 GND、根本没接 MCU** ——
 *     电池与 +5V 轨之间**没有任何可控开关**。
 *     ⇒ 软件关机只能 `esp_deep_sleep()`（RTC 域保持 ≈50~150 µA），
 *       **做不到真断电**。真断电必须物理开关串在电池线上。
 *
 *  ── 关机/开机方案（10-04 拍板：不做物理开关）────────────────
 *  ESP32-S3 的 RTC 引脚**只有 GPIO0~GPIO21**：
 *      · IO0（板载 BOOT 键）∈ RTC 域 ⇒ **能从 deep sleep 唤醒**
 *      · IO45/IO46（扩展座）∉ RTC 域 ⇒ 唤醒不了
 *      · EN/RESET 键走的是电源复位脚，**不参与 ext1**
 *  所以「开机键」只能用现成的 BOOT 键，零硬件、零开孔。
 *
 *  ⚠️⚠️⚠️ 唤醒极性必须是 `ESP_EXT1_WAKEUP_ANY_LOW`（**按住**才醒）⚠️⚠️⚠️
 *     ★ 10-04 血泪：v1.32 配的是 ANY_HIGH，结果兰兰实测「关机后马上又自己
 *       开机」。根因是 **EXT1 判的是【当前电平】，不是【有没有变化】**
 *       （esp_sleep.h:365 原文：Once selected pins go into the state given
 *       by level_mode, the chip will be woken up）。
 *       我当时按【边沿】想：以为「按住时 IO0 低、不满足 ANY_HIGH，
 *       松开变高才触发」。实际是 BOOT 键松开时 IO0 已被内部上拉到高，
 *       进 deep sleep 那一瞬间电平就已满足 ⇒ 立刻自己醒回来。
 *       ⇒ 正确：常态高（睡得着）+ 按住变低（唤醒）= **ANY_LOW**。
 *
 *  ⛔ 随之而来的代价（必须告诉用户）：唤醒时用户【正按着 BOOT】，
 *     IO0 为低 ⇒ ESP32 复位采样会判成「进下载模式」。
 *     ⇒ 开机要【按住 BOOT 键，等屏幕亮起再松开】；
 *       若没刷出来，松开再按一下 RESET 键就恢复。
 *     这是「拿 BOOT 键当开关」的固有限制 —— 它本来就是下载模式引脚，
 *     板上没有第二个 RTC 按键可当开机键。
 * ============================================================ */

/* ---- 初始化（开机调一次，顺序在 nvs_flash_init 之后）---- */
esp_err_t app_pwr_init(void);

/* ============================================================
 *  电量检测（IO8 / BAT_ADC）
 * ============================================================ */

/* 电池电压（mV，已按原理图 2×100K 分压还原回电池侧）。
 * 返回 0 = ADC 没初始化成功或读数不可信。*/
int  app_pwr_batt_mv(void);

/* 电量百分比 0~100。走锂电放电曲线的分段线性查表，不是 mv/42。
 * 内部每 5 秒才真读一次 ADC，中间返回缓存（省电 + 稳定）。*/
int  app_pwr_batt_pct(void);

/* 正在充电吗？**没有硬件信号**（TP4054 的 CHRG 脚没引到 MCU），
 * 所以这里只能给一个诚实的启发式：电压顶到 4.0V 以上算"接近满充"。
 * 界面别拿它当"充电中"的确定依据。*/
bool app_pwr_batt_charging(void);

/* 电池是否存在。
 * ★★ 别再用「电压 > 3300mV」当判据 —— 10-04 兰兰实测它把
 *   「没插电池」判成了「94% 满电」。原理图（02_原理图.pdf 实读）给的答案：
 *     **TP4054 的 CE 脚硬接 GND = 充电常使能**，
 *     所以没插电池时它照样往 BAT 线灌充电电流，BAT+ 被顶到 4.2V 附近
 *     ⇒ 读数 4.15V 落在「满电」区间。
 *   而且**靠电压根本区分不了**：满电真电池 4.20V vs 空载 4.15~4.25V，
 *   差距比 ADC 的 ±20mV 噪声还小；TP4054 的 CHRG1 脚又没引到 MCU
 *   ⇒ 硬件上不存在「电池在不在」的电平判据。
 * ⇒ 只能让使用者自己声明。默认走自动（3300mV 界），
 *   界面「状态页 → 电池那一行」点一下即可手动纠正。*/
bool app_pwr_batt_present(void);

/* 手动声明「有/无电池」。界面上的点击会调它。
 * ⚠️ 只改本次运行的判断，不写 NVS —— 电池是插拔动作，
 *   固化到 flash 反而会出现「换了电池还记着上一块」的怪事。*/
void app_pwr_batt_set_present(bool present);

/* 这次判断是「手动声明」的吗（false = 自动判据）。界面用它决定提示语。*/
bool app_pwr_batt_is_manual(void);

/* 低电阈值（mV，低于此值判定为低电）。默认 3650。*/
int  app_pwr_low_mv(void);
void app_pwr_set_low_mv(int mv);

/* ---- 每秒调一次：低电时自动关机（到点只做一次）----
 * 放在 stat_timer_cb 里调，页面无关。*/
void app_pwr_tick(void);

/* ============================================================
 *  关机 / 开机
 * ============================================================ */

/* 关机：关屏 → 关功放 → 关 WiFi → deep sleep。
 * ★ 不返回（进 deep sleep 后 CPU 停在这里）。
 * 唤醒后从 esp_app_main() 重新开始，等价于一次冷启动。*/
void app_pwr_shutdown(void);

/* 上次是不是「关机后唤醒」起来的（用于开机时跳过 splash 或提示）*/
bool app_pwr_woke_from_shutdown(void);

/* ============================================================
 *  板载 RGB 状态灯（IO40，XL-5050RGBC-WS2812B，单 IO 串行）
 * ============================================================
 *  10-04 之前固件里从没点亮过它（PIN_LED_RGB 只在头文件出现过）。
 *  灯在板上是白色 LED 上再套三色胶，UI 上做状态提示正合适。
 *  ★ 驱动在 app_led.c（走 RMT 硬件时序，软件微秒做不出 400ns 的 T0H）。*/

typedef enum {
    APP_LED_OFF = 0,
    APP_LED_WIFI,      /* 联网成功：绿常亮 */
    APP_LED_LINKING,   /* 正在连接：琥珀呼吸 */
    APP_LED_PLAYING,   /* 正在放音：青色呼吸 */
    APP_LED_FAV,       /* 收藏了这台：金色闪一下 */
    APP_LED_LOW_BATT,  /* 低电：红色慢闪 */
} app_led_mode_t;

/* 初始化 RMT 通道。开机调一次，失败不致命（灯不亮而已）。*/
void app_led_init(void);

void app_led_set_mode(app_led_mode_t m);
void app_led_set_enabled(bool on);   /* 关灯（夜里/低电自动关）*/

/* 亮度 0~100（内部按 0~255 限幅）。默认 30。*/
void app_led_set_bright(int pct);
int  app_led_get_bright(void);
