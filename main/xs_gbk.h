#pragma once

#include <stddef.h>

/* ============================================================
 *  GB2312 → UTF-8 转码
 * ============================================================
 *  为什么需要（背景见 _gen_gbk.py 的长注释）：
 *    腾讯/新浪行情接口返回的中文名是 GBK 编码，板上没有解码能力，
 *    而「自由添加自选股」的名称是运行时才知道的，内置名称表覆盖不到。
 *    ⇒ 用一张 17.7 KB 的 GB2312 码表在板上转码。
 *
 *  ★ 只覆盖 GB2312 的 6763 个常用汉字 ——
 *    股票名 / ETF 名 / 指数名用的汉字几乎全在范围内。
 *    表外的字回退成 '?'（不会崩，也不会显示成错字）。
 * ============================================================ */

/* 把 src[0..n) 的 GB2312 字节串转成 UTF-8 写进 dst（含结尾 '\0'）。
 * 返回写入的字节数（不含结尾）。dst 至少需要 n*2+1 字节才绝对安全，
 * 实际上汉字最多 2 字节 GBK → 3 字节 UTF-8，所以 3/2 倍即可。
 * ★ ASCII 字节原样透传（行情里的数字/符号就是 ASCII）。*/
int xs_gbk_to_utf8(const char *src, int n, char *dst, size_t cap);
