/*
 * 拾声 · 极简网络取数（明文 HTTP + 迷你 JSON / 分隔文本取值）   v1.0
 * ============================================================
 *  给「天气时钟」「股票行情」两个 App 共用。只做两件事：
 *    ① 把 http:// 的响应体拉进一块调用者给的缓冲；
 *    ② 从响应体里按 key 抠出想要的那几个值。
 *
 *  ★★ 为什么【只做明文 http】、不做 https：
 *    10-08 真机实测（`lq_mem` 命令）：内部 RAM 最大连续块只有 31.7 KB，
 *    而一次 TLS 握手要 16~40 KB 【连续】内存 ⇒ 必然失败。
 *    国内行情/天气接口本来就是明文 http，够用，也就不需要证书包。
 *    ⚠ 哪天想把 LVGL 池再腾出来也别急着开 TLS —— 先看 largest（不是 free），
 *      那个数才是 TLS 的入场券。
 *
 *  ★★ 为什么不用 cJSON：
 *    ① 工程里没引这个组件，加一个就是多一份发布依赖与体积；
 *    ② 它按节点 malloc，小块碎片对这块只剩几十 KB 内部 RAM 的板子是负担；
 *    ③ 我们要的两类响应结构完全固定（itboy 的 JSON、腾讯的 ~ 分隔文本），
 *       字符串扫描足够，而且【零堆分配】。
 *
 *  ★ 线程安全：本文件全是纯函数，不持有任何全局状态，可从任意任务调用。
 *    （esp_http_client 自身允许多实例并发，但本工程用不到。）
 * ============================================================ */
#pragma once

#include <stdbool.h>
#include <stddef.h>

/* ------------------------------------------------------------
 *  ① 明文 HTTP GET —— 响应体写进 buf（末尾补 '\0'）
 * ------------------------------------------------------------
 *  返回：>0 = 实际写入的字节数（不含结尾 '\0'）；
 *        -1 = 失败（参数不对 / 不是 http:// 开头 / 没联网 /
 *             超时 / 非 200 / 响应体超过 cap-1 被截断到上限）
 *
 *  ★ 会截断而不是失败：cap 用满是常见情形（接口偶尔多发几个字节的
 *    空白），调用者拿到的仍是可解析的前缀。想区分"截断了没"看返回值
 *    是否等于 cap-1。
 *  ★ 失败时 buf 里可能是半截内容 —— 调用者必须先看返回值再解析。
 */
int xs_http_get(const char *url, char *buf, size_t cap);

/* ------------------------------------------------------------
 *  ② 迷你 JSON 取值
 * ------------------------------------------------------------
 *  从 js 里取 "key" 后面的值写进 out：
 *    字符串值  "city":"上海"     → out = 上海（引号剥掉）
 *    数字/布尔 "pm25":34        → out = 34（原字面量）
 *
 *  ★ 带引号匹配：搜索模式是【"key" 六个字符】，所以 "city" 不会
 *    误命中 "citykey"（后面那个是 `y"` 不是 `"`），"time" 也不会
 *    命中 "updateTime"。这是刻意为之，不是巧合。
 *  ★ 不处理转义 / 嵌套 / 转义引号：本工程喂进来的接口里都没有。
 *  ★ 返回 false 表示"没这个 key"或"值不完整"，此时 out 是空串。
 */
bool xs_json_get(const char *js, const char *key, char *out, size_t cap);

/*  取数组里第 idx 个元素（0 起）的原文子串。
 *    形如  "forecast":[ {"ymd":"…"}, {"ymd":"…"} ]
 *    取 idx=1 → out = {"ymd":"…"}（含两端花括号）
 *  ★ 用法：先切出元素，再用 xs_json_get 在元素内部取值 ——
 *    因为 "type" "high" 这些 key 在每个元素里都出现，
 *    直接在整包里取只会拿到第一个（=今天）的。
 *  ★ 返回 false = 没这个 key / 数组里没这么多元素。
 */
bool xs_json_elem(const char *js, const char *key, int idx, char *out, size_t cap);

/*  取【顶层数组】里第 idx 个元素（0 起）的原文子串。
 *    新浪日K接口返回的就是顶层数组，没有 key：
 *      [ {"day":"2026-09-28","open":"3878.409","high":…}, {"day":…}, … ]
 *    取 idx=1 → out = {"day":"2026-09-29",…}
 *  ★ 与 xs_json_elem 的区别：那个要求数组挂在一个 "key" 下面
 *    （如 "forecast":[ … ]），这个直接从整串里第一个 '[' 开始数。
 *  ★ 同样返回 false = 没有这个元素 / 数据被截断。*/
bool xs_json_top_elem(const char *js, int idx, char *out, size_t cap);

/* ------------------------------------------------------------
 *  ③ 按 '~' 切分（腾讯行情接口的格式）
 * ------------------------------------------------------------
 *  v_sh000001="1~上证指数~000001~3811.36~…";
 *  取第 idx 个字段（0 起），越界返回 false。
 *
 *  ★★★ 为什么不能简单地按字节找 '~'：
 *    这段文本是 **GBK** 编码的（"上证指数" 是 C9CF D6A4 D6B8 CAFD）。
 *    GBK 双字节字符的【第二字节范围是 0x40~0xFE（除 0x7F）】——
 *    也就是说 **第二字节完全可能是 0x7E，那就正好是 '~'**。
 *    按字节切会把一个汉字劈成两半，还会凭空多出一个字段，
 *    后面所有字段的索引全部错位 ⇒ 取到的是别的数字，而且不报错。
 *    本函数遇到 >= 0x81 的字节就整体吞两个字节，从根上避开。
 *    （ASCII 与 '~' 恒 < 0x80，两者不会互相干扰。）
 */
bool xs_split_tilde(const char *s, int idx, char *out, size_t cap);

/* ------------------------------------------------------------
 *  ④ 抠数字（从 "高温 25℃" 这种带中文的字段里取 25）
 * ------------------------------------------------------------
 *  ★ 为什么需要：itboy 的 high/low 字段长这样 —— "高温 25℃"、"低温 16℃"，
 *    数字外面裹着中文。只取数字部分即可，界面自己加 "°"。
 *  ★ 允许一位小数（温度有 25.5 这种）。取不到数字则 out 为空串。
 */
void xs_pick_num(const char *src, char *out, size_t cap);
