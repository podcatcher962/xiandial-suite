#pragma once

#include <stdbool.h>

/* ============================================================
 *  拾声 · 语音播报（voice_speak）
 * ============================================================
 *  用【预生成的语音原子】拼出一句话来播。
 *
 *  ★★ 为什么是"原子 + 拼接"而不是"整句合成"：
 *    要播的内容是动态的（"现在 15 点 20 分，晴 25 度"），不可能预生成每句话；
 *    板上又没有 TTS 引擎，在线 TTS 也试过（有道词典发音只认个别词条、
 *    百度的已改成要 token 的 JSON）⇒ 只能预生成最小发音单元，运行时拼。
 *
 *  ★★ 为什么拼接在板上做（而不是预生成所有组合）：
 *    时间 24×60、温度 100 档、天气 20 种 —— 组合数是天文数字。
 *    板上有 SD 卡可写，读几段小 mp3 顺序写出一个临时文件即可。
 *    临时文件的 mp3 都已【剥掉 ID3】，所以是纯字节拼接，解码器能连续解。
 *
 *  ★ 非阻塞：内部起一次性任务（SD 读写 + 播放启动几百毫秒，不占 LVGL 任务）。
 *  ★ 播报会临时解除静音（xs_cfg_audio_boost），播完自动还原 ——
 *    这样"默认声音关闭"和"点了播报要听得见"可以共存。
 * ============================================================ */

/* 播报 atoms（语音原子名，不含路径与扩展名），如
 *   {"p_bj","n15","u_dian","n20","u_fen"}
 * 实现会立刻把名字拷进内部缓冲，所以调用方传栈上的字符串也安全。
 * ★ 返回 false 的情形：参数为空 / 正在播报中 / 任务创建失败。*/
bool voice_speak(const char *const *atoms, int n);

/* 是否正在播报（UI 可据此显示"播报中…"或忽略重复点击）*/
bool voice_speak_busy(void);

/* 立即停止播报（退出 App / 切产品时调）*/
void voice_speak_stop(void);
