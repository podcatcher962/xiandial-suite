/*
 * 拾声 · 多产品外壳 (ui_shell)
 * ============================================================
 *  一块板装四个产品：开机进【主菜单】（2×2 宫格），点卡进入对应 App，App 内可退回主菜单。
 *
 *  ★ 为什么要有这一层（而不是把天气直接塞进灵签）：
 *    灵签本来就不是"独立程序"，它是把拾声的界面层换掉了 ——
 *    显示/触摸/字库/音频/电源/WiFi 全是共享底座。
 *    既然底座本来就能跑多个界面，那就把"界面层"正式做成可插拔的 App。
 *
 *  ★★ 一条硬规矩：**进入才创建、离开即销毁**。
 *    内部 SRAM 只有 ~98 KB 余量（10-08 实测），LVGL 池 64 KB。
 *    两个 App 的界面同时活着 ⇒ 对象池立刻见底 ⇒ release 构建下静默崩溃。
 *    所以主菜单屏常驻（很小），App 屏进出即建即删，任何时刻只活一个。
 *
 *  ★ 调用约定（很重要）：
 *    这两个函数都直接操作 LVGL 对象，
 *    ⇒ 必须在【LVGL 任务里】或【持有 lvgl_port_lock() 的上下文】调用。
 *      从按钮回调里调用天然满足（回调就跑在 LVGL 任务里），不要再套一层 lock。
 * ============================================================ */
#pragma once

/* 建立主菜单并切到它。★ 在 app_main 里【替代】ui_lingqian_init()。
 *  须在 app_display_init() 之后调用。*/
void ui_shell_init(void);

/* 从任意 App 退回主菜单：先切屏、再销毁该 App（顺序不能反）。
 *  App 内部（如灵签的设置面板）调它即可退出。*/
void ui_shell_back(void);

/* 直接进入第 idx 个产品（0 = 拾声电台，1 = 灵签，2 = 天气，3 = 股票）。
 * ★ 顺序 10-08 晚变过（拾声电台置顶）—— 老脚本里写死 app_open 0 的会打到电台。
 * ★ 给串口调试用（`app_open <n>`）——这块板没有物理手指，
 *   验证主菜单→产品的跳转只能靠命令，否则每轮都得找人点一下。
 * ★ 传越界值或未实现的产品：安全返回（未实现的会弹"还没做好"）。
 * ★ 已经在某个产品里时，会【先退出当前产品】再进新的。*/
void ui_shell_launch(int idx);

/* ★ 10-08 调试用：直接弹开首页右上角的「设 置」面板。
 * 为什么需要它：面板的入口是"点那个按钮"，而这块板【没有物理手指】，
 * 串口也注入不了触摸 —— 不给一条命令就【看不到这个新面板长什么样】，
 * 只能靠猜。与灵签的 lq_demo 是同一个套路（那也是个纯调试跳页口）。
 * ★ 必须在 LVGL 锁内调用；且当前要停在主菜单（面板是挂在主菜单屏上的）。*/
void ui_shell_demo_cfg(void);

/* ★ 10-08 调试用：把设置面板的滚动内容层滚到 y（配合 ui_shell_demo_cfg）。
 * 为什么需要：设备信息十行在面板下半屏，而面板可滚、板子没有物理手指 ——
 * 不开这个口就【看不到下半屏到底画成什么样】。先 ui_shell_demo_cfg() 再调它。
 * ★ 必须在 LVGL 锁内调用。面板没开着时安全返回（只打一条 warning）。*/
void ui_shell_demo_cfg_scroll(int y);

/* ★ 10-08 调试用：代按一次设置面板里的「配 网」键（开/关 SoftAP 配网热点）。
 * 为什么需要：那个键的入口是手指，板子没有物理手指。
 * ★ 走的是按钮【同一个回调】，不是另抄一份动作序列。
 *   须先 ui_shell_demo_cfg()，并在 LVGL 锁内调用。*/
void ui_shell_demo_prov(void);

/* ★ 10-08 调试用：代按设置面板右上角的 ✕（关闭）。
 * 为什么需要：关闭路径会先 lv_timer_del 再异步删面板（防悬空指针），
 * 而这条路"一次都没在真机上走"过 —— 面板能用命令开、却没命令能关。
 * 走的是 ✕ 按钮【同一个回调】。须先 ui_shell_demo_cfg()。*/
void ui_shell_demo_cfg_close(void);

/* ★★ 10-08 晚 调试用：代按主菜单左上角的「关 机」，但【只上膛，不真关】。
 * 为什么只上膛：真按第二下进 deep sleep，唯一唤醒源是板载 BOOT 键，
 *   而这块板在阳台机上没手指按 ⇒ 会"睡死"到有人来看它为止。
 * 验证内容 = 两步确认的全部：标签变"再点一次" + 4 秒自动回弹。
 * 走的是 power_off_cb【同一个回调】。须在主菜单（先 app_home），LVGL 锁内调用。*/
void ui_shell_demo_power(void);

/* ★ 10-08 调试用：把【当前活动屏】的直接子对象（坐标/尺寸/是否隐藏）打到日志。
 * 用来回答"对象明明建了，为什么屏上没有"——父对象不是活动屏 / 被 HIDDEN /
 * 坐标尺寸为 0，这三种读代码看不出来、截图上只表现为"什么都没有"。*/
void ui_shell_demo_dump(void);

